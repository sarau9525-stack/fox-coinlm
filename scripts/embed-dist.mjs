import fs from 'node:fs';
import path from 'node:path';

const distDir = path.resolve(process.cwd(), 'dist');
const outFile = path.resolve(process.cwd(), 'functions', 'generatedAssets.ts');

function detectMimeType(filePath, buf) {
  // Check magic bytes first for images so WebP/JPEG/PNG always get exact Content-Type
  if (buf && buf.length >= 12) {
    if (
      buf[0] === 0x52 &&
      buf[1] === 0x49 &&
      buf[2] === 0x46 &&
      buf[3] === 0x46 &&
      buf[8] === 0x57 &&
      buf[9] === 0x45 &&
      buf[10] === 0x42 &&
      buf[11] === 0x50
    ) {
      return 'image/webp';
    }
    if (buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) {
      return 'image/jpeg';
    }
    if (buf[0] === 0x89 && buf[1] === 0x50 && buf[2] === 0x4e && buf[3] === 0x47) {
      return 'image/png';
    }
  }

  const ext = path.extname(filePath).toLowerCase();
  switch (ext) {
    case '.html':
      return 'text/html; charset=utf-8';
    case '.js':
    case '.mjs':
      return 'application/javascript; charset=utf-8';
    case '.css':
      return 'text/css; charset=utf-8';
    case '.json':
      return 'application/json; charset=utf-8';
    case '.svg':
      return 'image/svg+xml';
    case '.png':
      return 'image/png';
    case '.jpg':
    case '.jpeg':
      return 'image/jpeg';
    case '.webp':
      return 'image/webp';
    case '.ico':
      return 'image/x-icon';
    case '.woff2':
      return 'font/woff2';
    case '.woff':
      return 'font/woff';
    default:
      return 'application/octet-stream';
  }
}

function walkDir(dir, baseDir = dir) {
  let results = [];
  if (!fs.existsSync(dir)) return results;
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    const relPath = '/' + path.relative(baseDir, fullPath).replace(/\\/g, '/');
    if (entry.isDirectory()) {
      results = results.concat(walkDir(fullPath, baseDir));
    } else if (entry.isFile()) {
      if (entry.name === '_headers' || entry.name === '_routes.json') continue;
      results.push({ urlPath: relPath, fullPath });
    }
  }
  return results;
}

const files = walkDir(distDir);
const assetEntries = [];
let totalBytes = 0;

for (const file of files) {
  const buf = fs.readFileSync(file.fullPath);
  totalBytes += buf.length;
  const contentType = detectMimeType(file.fullPath, buf);
  const base64 = buf.toString('base64');
  const immutable = file.urlPath.startsWith('/assets/');
  assetEntries.push(
    `  ${JSON.stringify(file.urlPath)}: { contentType: ${JSON.stringify(
      contentType
    )}, base64: ${JSON.stringify(base64)}, immutable: ${immutable} }`
  );
}

const output = `// Auto-generated by scripts/embed-dist.mjs during npm run build
export interface EmbeddedAsset {
  contentType: string;
  base64: string;
  immutable?: boolean;
}

export const STATIC_ASSETS: Record<string, EmbeddedAsset> = {
${assetEntries.join(',\n')}
};
`;

fs.writeFileSync(outFile, output, 'utf8');
console.log(
  `✓ Embedded ${files.length} static assets (${(totalBytes / 1024 / 1024).toFixed(
    2
  )} MB raw) into functions/generatedAssets.ts`
);
